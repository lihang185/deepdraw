static void verify_runtime(const wchar_t* name, const char* expected) {
    wchar_t path[32768];
    HMODULE dll=GetModuleHandleW(name);
    DWORD size=GetModuleFileNameW(dll,path,32768);
    if (!dll || !size || size>=32768) throw std::runtime_error("Cannot locate SketchUp runtime DLL");
    auto bytes=py::module_::import("pathlib").attr("Path")(std::wstring(path,size)).attr("read_bytes")();
    auto hash=py::module_::import("hashlib").attr("sha256")(bytes).attr("hexdigest")().cast<std::string>();
    if (hash!=expected) throw std::runtime_error("SketchUp runtime version mismatch: install the DLL pair documented in native/sketchup/README.md");
}
